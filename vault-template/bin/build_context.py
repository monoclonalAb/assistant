#!/usr/bin/env python3
"""Assemble .hermes.md, the project context Hermes injects into every session.

    .hermes.md = system/chat.md + profile.md + now.md + tasks.md

Each part is trimmed to a budget so the file stays under Hermes's default
20,000-character context-file cap. Truncation warnings go to stderr and the
exit code is 2, so the nightly job knows to shorten a file and rebuild.

Inside the Hermes container the result is also run through Hermes's own
prompt-injection scanner. If it matches, Hermes would replace the WHOLE file
with a [BLOCKED] notice and Jarvis would lose its memory snapshot, so we
exit 3 and name the offending source file instead.

Stdlib only. Run from anywhere: python3 bin/build_context.py
"""

from __future__ import annotations

import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".hermes.md"

# (source file, snapshot heading or None for the preamble, character budget)
PARTS = [
    ("system/chat.md", None, 5000),
    ("profile.md", "Profile", 8000),
    ("now.md", "Now", 3000),
    ("tasks.md", "Tasks", 2500),
]

FRONTMATTER = re.compile(r"\A---\n.*?\n---\n", re.S)
HERMES_INSTALL = Path("/opt/hermes")


def threat_scanner():
    """Hermes's context-file scanner when running in its container, else None."""
    if not HERMES_INSTALL.is_dir():
        return None
    sys.path.insert(0, str(HERMES_INSTALL))
    try:
        from tools.threat_patterns import scan_for_threats
    except Exception:
        return None
    return lambda text: scan_for_threats(text, scope="context")


def load(rel: str) -> str:
    path = ROOT / rel
    if not path.exists():
        return ""
    return FRONTMATTER.sub("", path.read_text(encoding="utf-8"), count=1).strip()


def demote(text: str) -> str:
    """Drop the file's own H1 and push other headings down one level."""
    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    out = []
    for line in lines:
        match = re.match(r"^(#{1,5}) ", line)
        out.append("#" + line if match else line)
    return "\n".join(out).strip()


def trim(text: str, budget: int, rel: str, warnings: list[str]) -> str:
    if len(text) <= budget:
        return text
    cut = text.rfind("\n", 0, budget - 120)
    warnings.append(f"{rel}: {len(text)} chars, over its {budget}-char budget; truncated")
    return text[: cut if cut > 0 else budget - 120].rstrip() + f"\n\n…[truncated; read /workspace/{rel} for the rest]"


def main() -> int:
    warnings: list[str] = []
    stamp = datetime.now().astimezone().strftime("%A %Y-%m-%d %H:%M %Z")
    scan = threat_scanner()
    blocked: list[str] = []
    # Plain text, not an HTML comment: Hermes blocks comments containing words like "system".
    sections = [
        "_Generated by bin/build_context.py. Edit the source files (chat.md, profile.md, "
        "now.md, tasks.md) and rebuild; don't edit this file._"
    ]
    for rel, heading, budget in PARTS:
        text = load(rel)
        findings = scan(text) if scan else []
        if findings:
            blocked.append(f"{rel}: {', '.join(findings)}")
        if heading is None:
            sections.append(trim(text, budget, rel, warnings))
            sections.append(
                f"# Memory snapshot\nGenerated {stamp}. These are copies of the vault files "
                "as of then; read the files for anything time-sensitive."
            )
            continue
        sections.append(f"## {heading} (/workspace/{rel})\n\n" + trim(demote(text), budget, rel, warnings))

    output = "\n\n".join(sections) + "\n"
    if scan and not blocked:
        findings = scan(output)
        if findings:
            blocked.append(f".hermes.md (assembled): {', '.join(findings)}")
    if blocked:
        for item in blocked:
            print(f"ERROR: Hermes would block .hermes.md because of {item}. Reword that text "
                  "(e.g. paraphrase quoted instructions) and rebuild.", file=sys.stderr)
        return 3

    OUT.write_text(output, encoding="utf-8")
    size = OUT.stat().st_size
    print(f"wrote {OUT.relative_to(ROOT)} ({size} bytes)")
    for warning in warnings:
        print(f"WARNING: {warning}", file=sys.stderr)
    return 2 if warnings else 0


if __name__ == "__main__":
    sys.exit(main())
